import assert from 'node:assert/strict';
const msg = (id, is_user, mes) => ({ extra: { layered_memory_id: id }, send_date: id, is_user, mes });
const chat = [msg('a', false, '『书店｜2024-07-17｜12:00-12:10』\n两人一起吃饭。'), msg('u', true, '一个月后，回到书店。')];
const context = { chat, chatMetadata: {}, extensionSettings: {}, name1: '玩家', name2: '测试', saveMetadata: async () => {}, saveSettingsDebounced() {}, chatCompletionSettings: { prompts: [], prompt_order: [] } };
globalThis.SillyTavern = { getContext: () => context };
const { messageContentFingerprint } = await import('../src/ids.js');
const { buildCoreMemoryParts, renderCoreMemoryPayload, setActiveGenerationType, clearActiveGenerationType } = await import('../src/inject.js');
const { DEFAULT_SETTINGS, EMPTY_CHAT_DATA } = await import('../src/constants.js');
const settings = structuredClone(DEFAULT_SETTINGS);
context.extensionSettings.layered_memory = settings;
const data = EMPTY_CHAT_DATA(); context.chatMetadata.layered_memory = data;
data.narrative_summaries = [{ messageKey: 'a', contentFingerprint: messageContentFingerprint(chat[0]), messageIndex: 0, role: 'assistant', summary: '两人一起吃饭。', segments: [{ time_change: null, events: [{ text: '两人一起吃饭。', evidence: '两人一起吃饭。' }] }] }];
let parts = buildCoreMemoryParts({ data, settings, context });
assert.equal(parts.timeline.current.date, '2024-08-17');
assert.match(parts.temporal, /距今31天/u);
assert(!parts.temporal.includes('两人一起吃饭'), 'clock must not duplicate recent raw events');
assert(!parts.raw.includes('一个月后'), 'current user input must not be duplicated into raw history');
assert.match(renderCoreMemoryPayload({ data, settings, context }), /唯一当前剧情日期：2024-08-17/u);
settings.timelineEnabled = false;
assert.equal(buildCoreMemoryParts({ data, settings, context }).temporal, '');
settings.timelineEnabled = true;
chat.push({ ...msg('pending', false, '『书店｜2024-09-17｜12:00』'), swipes: [], swipe_id: 0 });
setActiveGenerationType('swipe', { excludeTrailingAssistant: true });
parts = buildCoreMemoryParts({ data, settings, context });
assert.equal(parts.timeline.current.date, '2024-08-17', 'pending candidate must not advance the timeline');
clearActiveGenerationType();
console.log('Timeline injection: pending user jump, nonduplicated raw, actual core payload, disable switch and pending-swipe projection passed.');
// A stopped stream's visible partial header is retained as text but cannot advance the clock.
const { recordTimelineReceipt } = await import('../src/timeline-receipt.js');
chat.pop();
const partial = msg('part', false, '『书店｜2024-10-17｜12:00』\n他刚开口'); chat.push(partial);
assert.equal(recordTimelineReceipt(context, 2, { message: {}, swipeId: undefined, stopped: true }), false);
assert.equal(recordTimelineReceipt(context, 2, { message: partial, swipeId: undefined, stopped: true, request: { metadata: {} } }), false);
assert.equal(recordTimelineReceipt(context, 2, { message: partial, swipeId: undefined, stopped: true, request: { metadata: context.chatMetadata } }), true);
assert.equal(buildCoreMemoryParts({ data, settings, context }).timeline.current.date, '2024-08-17');
assert.equal(recordTimelineReceipt(context, 2, { message: partial, swipeId: undefined, stopped: false, request: { metadata: context.chatMetadata } }), true);
assert.equal(buildCoreMemoryParts({ data, settings, context }).timeline.current.date, '2024-10-17');
